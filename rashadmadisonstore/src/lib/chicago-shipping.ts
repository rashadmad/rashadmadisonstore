type ShippingAddress = {
  country_code?: string | null
  province?: string | null
  postal_code?: string | null
}

export function isChicagoAreaAddress(
  address?: ShippingAddress | null
): boolean {
  if (address?.country_code?.trim().toLowerCase() !== "us") {
    return false
  }

  const province = address.province?.trim().toLowerCase()
  if (province && !["il", "us-il", "illinois"].includes(province)) {
    return false
  }

  const postalCode = address.postal_code?.trim() ?? ""
  if (!/^\d{5}(-\d{4})?$/.test(postalCode)) {
    return false
  }

  return eligiblePostalCodes.has(postalCode.slice(0, 5))
}
